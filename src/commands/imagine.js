import sharp from 'sharp';
import config from '../config/config.js';
import logger from '../utils/logger.js';
import {makeLimiter} from '../services/publicAi.js';
import {generateImage,parsePrompt} from '../services/imageGen.js';
const limiter=makeLimiter('IMAGINE','IMAGINE_PER_HOUR',60,1);
const users=new Map();
function userLimit(u,now=Date.now()){const a=(users.get(u)||[]).filter(t=>now-t<300000);if(a.length>=3)return false;users.set(u,[...a,now]);if(users.size>5000)users.clear();return true;}
export function cleanPrompt(args){return args.join(' ').replace(/\s+/g,' ').trim().slice(0,300);}
export default {name:'imagine',aliases:['img','aiimage'],category:'Image',description:'Generate an image from text (free public AI)',usage:'imagine [dev|sd3|schnell|pollinations:] <description>',
async run(ctx){
  const prompt=cleanPrompt(ctx.args||[]);
  if(!prompt)return ctx.reply('Usage: '+config.prefix+'imagine a red car on a rainy neon street');
  if(!userLimit(ctx.sender))return ctx.reply('Limit: 3 images per 5 minutes. Try again shortly.');
  if(!limiter.ok())return ctx.reply('Image generation is busy or turned off right now. Try again in a minute.');
  await limiter.run(async()=>{
    const {prefer,prompt:p}=parsePrompt(prompt);
    let buf,src;
    try{({buf,source:src}=await generateImage(p,{prefer,log:(m)=>logger.warn(m)}));}
    catch(e){return ctx.reply('Image generation failed: all free AI image services are busy or out of free quota right now ('+(e.failed||[]).length+' tried). Nothing was charged. Try again in a few minutes.');}
    let out;try{out=await sharp(buf,{limitInputPixels:4096*4096}).jpeg({quality:90}).toBuffer();}catch{return ctx.reply('Image generation failed. Try again.');}
    await ctx.sock.sendMessage(ctx.jid,{image:out,caption:'Prompt: '+p+'\nGenerated by free public AI ('+src+'). Your text was sent to that third-party service.'},{quoted:ctx.msg});
  });
}};
