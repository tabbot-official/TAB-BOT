  description: 'Style your text in 30+ fancy fonts',
  usage: 'fancy <style> <text> | fancy all <text> | fancy list',
  async run(ctx) {
    if (!featOn('fancy')) return ctx.reply('Fancy fonts are turned off right now.');
    const [style, ...rest] = ctx.args;
    const text = rest.join(' ').trim();
    if (!style || style === 'list') return ctx.reply('*Fancy styles:* ' + Object.keys(STYLES).join(', ') + '\n\nUse: /fancy <style> <text> or /fancy all <text>');
    if (!text) return ctx.reply('Give me text to style. Example: /fancy script Tab');
    if (text.length > 100) return ctx.reply('Keep it under 100 characters.');
    if (style === 'all') {
      const out = Object.entries(STYLES).map(([n, f]) => '*' + n + ':* ' + f(text)).join('\n');
      return ctx.reply(out);
    }
    const f = STYLES[style.toLowerCase()];
    if (!f) return ctx.reply('Unknown style "' + style + '". Try /fancy list.');
    return ctx.reply(f(text));
  },
